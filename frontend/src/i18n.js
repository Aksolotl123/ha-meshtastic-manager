export function makeT(language) {
  const dict = language && language.startsWith("pl") ? pl : en;
  const t = (key) => dict[key] ?? en[key] ?? key;
  t.lang = dict === pl ? "pl" : "en";
  t.section = (name) => {
    if (dict === pl && sectionsPl[name]) return sectionsPl[name];
    return humanize(name);
  };
  return t;
}

export function humanize(name) {
  const s = name.replace(/_/g, " ");
  return s.charAt(0).toUpperCase() + s.slice(1);
}
